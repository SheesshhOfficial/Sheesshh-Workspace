// Synthetic workspace and terminals only. No provider login or real agent launch.
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, cp } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect } from '@playwright/test';
import { createService } from '../server.mjs';
import { launchBrowser } from './browser.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
await mkdir(path.join(root, '.cache'), { recursive: true });
const repo = await mkdtemp(path.join(root, '.cache/ecc-ui-'));
await mkdir(path.join(repo, 'workspace')); await mkdir(path.join(repo, '.sheesshh'));
await writeFile(path.join(repo, 'workspace/workspace.json'), '{"entities":[]}');
await writeFile(path.join(repo, '.sheesshh/sessions.json'), JSON.stringify([{ id: 'ecc-review', name: 'ECC isolated review', agent: 'codex', cwd: repo, open: true, status: 'stopped', bypass: false, cols: 90, rows: 28, createdAt: '2026-10-24T00:00:00Z', updatedAt: '2026-10-24T00:00:00Z' }]));
await cp(path.join(root, 'public/ecc'), path.join(root, 'dist/ecc'), { recursive: true });
const catalog = JSON.parse(await readFile(path.join(root, 'dist/ecc/catalog.json'), 'utf8'));
if (catalog.itemFiles) catalog.items = (await Promise.all(catalog.itemFiles.map(file => readFile(path.join(root, 'dist/ecc', file), 'utf8').then(JSON.parse)))).flat();
const item = catalog.items.find(item => item.id === 'context:research') || catalog.items.find(item => item.kind === 'context');
assert.ok(item, 'catalog has a context instruction');
let service, browser;
const writes = [], errors = [], outbound = [];
try {
  service = await createService({ repo, uiDir: path.join(root, 'dist'), mcpOptions: { home: repo, env: {} } });
  service.sessions.launch = session => {
    session.status = 'running'; session.restoreError = null;
    session.process = { resize() {}, write(data) { writes.push(data); }, kill() { session.process = null; } };
    service.sessions.changed(session);
  };
  for (const session of service.sessions.items.values()) { await service.sessions.hydrate(session); service.sessions.launch(session); }
  browser = await launchBrowser();
  const page = await browser.newPage({ viewport: { width: 1380, height: 920 } });
  page.setDefaultTimeout(12000); page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => { window.eccCopied = ''; Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.eccCopied = text; } } }); });
  await page.goto(service.urls.workspace);
  await page.getByRole('button', { name: 'Toggle ecc', exact: true }).click();
  await expect(page.locator('.ecc-tabs button')).toHaveText(['Workflows', 'Library', 'My Kits']);
  await expect(page.getByRole('button', { name: 'Workflows', exact: true })).toHaveAttribute('aria-current', 'page');
  page.on('request', request => { if (!request.url().startsWith(service.origin) && !request.url().startsWith(service.contentOrigin)) outbound.push(request.url()); });
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search ECC', exact: true }).fill(item.name);
  const row = page.locator('.ecc-item').filter({ has: page.getByText(item.name, { exact: true }) }).first();
  await row.getByRole('button', { name: `Favorite ${item.name}`, exact: true }).click();
  await expect(row.getByRole('button', { name: `Unfavorite ${item.name}`, exact: true })).toBeEnabled();
  await row.getByRole('checkbox').check();
  await page.getByRole('textbox', { name: 'New kit name', exact: true }).fill('Review kit');
  await page.getByRole('button', { name: 'Save kit', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'New kit name', exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'My Kits', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review kit', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Expand ECC', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'ECC library' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog', { name: 'ECC library' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Close ECC', exact: true }).click();
  await page.getByRole('button', { name: 'Toggle ecc', exact: true }).click();
  await page.getByRole('button', { name: 'My Kits', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review kit', exact: true })).toBeVisible();
  await page.locator('.ecc-kit').getByRole('button', { name: 'Use once', exact: true }).click();
  await page.getByRole('textbox', { name: 'ECC task', exact: true }).fill('Inspect the README only; do not edit or install anything.');
  await page.getByRole('combobox', { name: 'ECC target chat', exact: true }).selectOption('ecc-review');
  await page.getByRole('button', { name: 'Prepare exact prompt', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'ECC prompt preview', exact: true })).toHaveValue(/ONE-TIME ECC REFERENCE/);
  assert.equal(writes.length, 0, 'browsing, favorites, kits and prepare never write to terminals');
  await page.getByRole('button', { name: 'Copy prompt', exact: true }).click();
  assert.match(await page.evaluate(() => window.eccCopied), /Inspect the README only/);
  assert.equal(writes.length, 0, 'copy does not dispatch');
  await page.screenshot({ path: path.join(root, '.cache/ecc-expanded.png'), fullPage: true });
  const send = page.getByRole('button', { name: 'Send once to selected chat', exact: true });
  await send.evaluate(element => { element.click(); element.click(); });
  await expect(send).toBeDisabled();
  await expect.poll(() => writes.filter(text => text.includes('ONE-TIME ECC REFERENCE')).length).toBe(1);
  await expect(page.locator('.ecc-use [role=status]')).toContainText('does not confirm task completion');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Close ECC', exact: true }).click();
  await page.getByRole('button', { name: 'Toggle conversation', exact: true }).click();
  const composer = page.getByRole('textbox', { name: 'Message Sheesshh', exact: true });
  await composer.fill('/ecc Review one document');
  await page.getByRole('button', { name: 'Send to Sheesshh', exact: true }).click();
  await expect(page.locator('.ecc-tabs')).toBeVisible();
  assert.equal(writes.filter(text => text.includes('ONE-TIME ECC REFERENCE')).length, 1, '/ecc opens UI without dispatch');
  await page.getByRole('button', { name: 'Close ECC', exact: true }).click();
  let ordinary;
  await page.route('**/api/coordinator', async route => { ordinary = route.request().postDataJSON(); await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ id: ordinary.id, status: 'completed', text: ordinary.text, result: 'Synthetic response' }) }); });
  await composer.fill('Ordinary message without ECC');
  await page.getByRole('button', { name: 'Send to Sheesshh', exact: true }).click();
  await expect.poll(() => ordinary?.text).toBe('Ordinary message without ECC');
  assert.deepEqual(ordinary.images, []);
  await page.getByRole('button', { name: 'Toggle ecc', exact: true }).click();
  await page.getByRole('button', { name: 'Expand ECC', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 720 });
  await expect(page.getByRole('button', { name: 'Close ECC', exact: true })).toBeVisible();
  assert.ok(await page.locator('.ecc-dialog').evaluate(element => element.getBoundingClientRect().right <= innerWidth));
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 1380, height: 920 });
  await page.screenshot({ path: path.join(root, '.cache/ecc-compact.png'), fullPage: true });
  assert.deepEqual(outbound, [], 'ECC causes no outbound network requests');
  assert.deepEqual(errors, []);
  console.log('ECC UI PASS: three tabs, search, private favorites/kits, expand/Escape, copy-only preview, explicit once send, /ecc routing, unchanged ordinary composer, narrow layout and no outbound requests.');
} finally { await browser?.close(); await service?.close(); }
